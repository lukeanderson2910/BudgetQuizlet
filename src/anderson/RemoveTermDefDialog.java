    private void removeButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeButtonActionPerformed
        String item = (String) termAndDefComboBox.getSelectedItem();
        String strippedHTML = item.replaceAll("<[^>]*>", "");
        for(int i = 0; i < set.getTerms().size(); i++) {
            String testedString = set.getTerms().get(i) + ": " + set.getDefinitions().get(i);
            if(testedString.equals(strippedHTML)) {
                set.getTerms().remove(i);
                set.getDefinitions().remove(i);
            }
        }
        this.dispose();
    }//GEN-LAST:event_removeButtonActionPerformed

