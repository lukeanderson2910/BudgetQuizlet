    private void addListeners(JTextField termTextField, JTextField definitionTextField) {
        termTextField.addFocusListener(new FocusListener() {
            @Override
            public void focusGained(FocusEvent e) {
                termTextField.setBackground(textFieldColor);
                definitionTextField.setBackground(textFieldColor);
                repaint();
            }

            @Override
            public void focusLost(FocusEvent e) {

            }

        });
        definitionTextField.addFocusListener(new FocusListener() {
            @Override
            public void focusGained(FocusEvent e) {
                definitionTextField.setBackground(textFieldColor);
                termTextField.setBackground(textFieldColor);
                repaint();
            }

            @Override
            public void focusLost(FocusEvent e) {

            }

        });
    }


    private void submitButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_submitButtonActionPerformed
        boolean submitable = checkIfEmpty();
        ArrayList<String> terms = new ArrayList();
        ArrayList<String> defs = new ArrayList();
        if (!submitable) {
            JOptionPane.showMessageDialog(this, "Please add information to all of the text fields!", "Submit error", JOptionPane.ERROR_MESSAGE);
        } else {
            for (JTextField termField : termFields) {
                terms.add(termField.getText());
            }
            for (JTextField defField : definitionFields) {
                defs.add(defField.getText());
            }
            String name = (String) JOptionPane.showInputDialog(this, "Enter a name for your new study set.", "Study Set Name", JOptionPane.PLAIN_MESSAGE, null, null, null);
            if (name.isEmpty() || name == null) {
                name = "My New Study Set " + (sets.size() + 1);
            }
            set = new StudySet(terms, defs, name);
            this.dispose();
        }
    }//GEN-LAST:event_submitButtonActionPerformed

