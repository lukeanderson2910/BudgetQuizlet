    private boolean checkIfEmpty() {
        boolean allHasInfo = true;
        for (JTextField textField : termFields) {
            if (textField.getText().isEmpty()) {
                textField.setBackground(Color.red);
                allHasInfo = false;
            }
        }

        for (JTextField textField : definitionFields) {
            if (textField.getText().isEmpty()) {
                textField.setBackground(Color.red);
                allHasInfo = false;
            }
        }
        return allHasInfo;
    }

