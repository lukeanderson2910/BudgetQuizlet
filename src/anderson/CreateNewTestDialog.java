    private void newTestButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_newTestButtonActionPerformed
        questions = (int) questionsSpinner.getValue();
        if (multipleChoiceComboBox.isSelected()) {
            questionTypes.add("M/C");
        }
        if (TFComboBox.isSelected()) {
            questionTypes.add("T/F");
        }
        if (writtenComboBox.isSelected()) {
            questionTypes.add("WT");
        }

        if (matchingComboBox.isSelected()) {
            if (!questionTypes.isEmpty()) {
                questionTypes.add("MC");
            } else if (questions % 5 == 0) {
                questionTypes.add("MC");
            } else {
                JOptionPane.showMessageDialog(this, "If you're only doing matching, then questions have to be a multiple of 5 (this is because of laziness + bad programming)", "Test error", JOptionPane.ERROR_MESSAGE);
            }
        }

        if (termRadioButton.isSelected()) {
            answerWith = "term";
        } else {
            answerWith = "definition";
        }
        if (!questionTypes.isEmpty()) {
            this.dispose();
        }
    }//GEN-LAST:event_newTestButtonActionPerformed

