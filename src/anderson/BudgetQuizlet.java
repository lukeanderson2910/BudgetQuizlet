    private void testButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_testButtonActionPerformed
        if (studySets.get(currentSet).getTerms().size() >= 4) {
            CreateNewTestDialog createDialog = new CreateNewTestDialog(this, true, studySets.get(currentSet));
            createDialog.setVisible(true);
            if (!createDialog.isCancelled()) {
                TestDialog test = new TestDialog(this, true, studySets.get(currentSet), createDialog.getAnswerWith(), createDialog.getQuestionTypes(), createDialog.getQuestions());
                test.setVisible(true);
            }
        } else {
            JOptionPane.showMessageDialog(this, "You need at least 4 terms and definitions to make a test!", "Unable to make test", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_testButtonActionPerformed

    private void matchingButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_matchingButtonActionPerformed
        if (studySets.get(currentSet).getTerms().size() >= 2) {
            MatchingDialog dialog = new MatchingDialog(this, studySets.get(currentSet));
            dialog.setVisible(true);
            if (!dialog.isCancelled()) {
                if (studySets.get(currentSet).getRecord() > dialog.getRecord() || studySets.get(currentSet).getRecord() == 0) {
                    studySets.get(currentSet).setRecord(dialog.getRecord());
                    JOptionPane.showMessageDialog(this, "Congrats! Your time of " + dialog.getRecord() + " is the fastest time for this set!");
                    save(false);
                } else {
                    JOptionPane.showMessageDialog(this, "Your time of " + dialog.getRecord() + " was too slow to beat the record of " + studySets.get(currentSet).getRecord());
                }
            }

        } else {
            JOptionPane.showMessageDialog(this, "Aye bluzz you need at least 2 terms in ur set to do ts :C", "Error Loading Matching", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_matchingButtonActionPerformed

    private void viewButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_viewButtonActionPerformed
        ArrayList<Object> setNames = new ArrayList();
        for (StudySet set : studySets) {
            setNames.add(set.toString());
        }
        String choice = (String) JOptionPane.showInputDialog(this, "What would you like to view?", "View", JOptionPane.PLAIN_MESSAGE, null, setNames.toArray(), null);
        if (choice != null) {
            for (int i = 0; i < studySets.size(); i++) {
                if (studySets.get(i).toString().equals(choice)) {
                    currentSet = i;
                    changeLabel(studySets.get(currentSet).toString());
                    break;
                }
            }
        }

    }//GEN-LAST:event_viewButtonActionPerformed

    private void themeButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_themeButtonActionPerformed
        String[] themes = {"Light", "Dark", "Nimbus"};
        String choice = (String) JOptionPane.showInputDialog(this, "What would you like your theme to be?", "Theme", JOptionPane.PLAIN_MESSAGE, null, themes, null);
        if (choice != null) {
            saveThemeChoice(choice, "savedTheme.thm");

            if (choice.equals("Light")) {
                FlatLightLaf.setup();
            } else if (choice.equals("Dark")) {
                FlatDarkLaf.setup();
            } else {
                changeToNimbus();
            }

            SwingUtilities.updateComponentTreeUI(this);
        }
    }//GEN-LAST:event_themeButtonActionPerformed

