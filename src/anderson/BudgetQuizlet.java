    private void addButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addButtonActionPerformed
        Object[] options = {"Study Set", "Term and Definition"};
        String choice = (String) JOptionPane.showInputDialog(this, "What would you like to add?", "Add", JOptionPane.PLAIN_MESSAGE, null, options, null);
        if (choice != null) {
            if (choice.equals("Term and Definition") && !studySets.isEmpty()) {
                NewTermDefDialog termDefDialog = new NewTermDefDialog(this, true);
                termDefDialog.setVisible(true);
                String term = termDefDialog.getTerm();
                String definition = termDefDialog.getDefinition();
                if (term != null && definition != null) {
                    if (!term.isBlank() && !definition.isBlank()) {
                        studySets.get(currentSet).addDefinition(definition);
                        studySets.get(currentSet).addTerm(term);
                    }
                }

            } else if (choice.equals("Study Set")) {
                NewStudySetDialog newStudySet = new NewStudySetDialog(this, true, studySets);
                newStudySet.setVisible(true);
                StudySet set = newStudySet.getSet();
                if (set != null) {
                    currentSet++;
                    studySets.add(set);
                    enableButtons();
                    changeLabel(studySets.get(currentSet).toString());
                    save(false);
                }

            } else {
                JOptionPane.showMessageDialog(this, "Please add a Study Set before doing that!", "Submit error", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_addButtonActionPerformed

    private void removeButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeButtonActionPerformed
        Object[] options = {"Study Set", "Term and Definition"};
        String choice = (String) JOptionPane.showInputDialog(this, "What would you like to remove?", "Remove", JOptionPane.PLAIN_MESSAGE, null, options, null);
        if (choice != null && !studySets.get(currentSet).getTerms().isEmpty()) {
            if (choice.equals("Term and Definition")) {
                RemoveTermDefDialog dialog = new RemoveTermDefDialog(this, true, studySets.get(currentSet));
                dialog.setVisible(true);
                if (studySets.get(currentSet).getTerms().isEmpty()) {
                    studySets.remove(currentSet);
                }
            }
            if (choice.equals("Study Set")) {
                RemoveStudySetDialog dialog = new RemoveStudySetDialog(this, true, studySets);
                dialog.setVisible(true);

                if (studySets.isEmpty()) {
                    changeLabel("None");
                    disableButtons();
                } else {
                    if (!dialog.isCancelled()) {
                        currentSet = studySets.size() - 1;
                        changeLabel(studySets.get(currentSet).toString());
                    }
                }
            }

        }
    }//GEN-LAST:event_removeButtonActionPerformed

