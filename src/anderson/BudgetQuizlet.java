    public void saveThemeChoice(String choice, String fileName) {

        File theme = new File(System.getProperty("user.dir") + File.separator + fileName);
        try {
            ObjectOutputStream outputStream = new ObjectOutputStream(new FileOutputStream(theme));
            outputStream.writeObject(choice);
            outputStream.close();
        } catch (FileNotFoundException ex) {
            Logger.getLogger(BudgetQuizlet.class.getName()).log(Level.SEVERE, null, ex);
        } catch (IOException ex) {
            Logger.getLogger(BudgetQuizlet.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

    public void loadThemeChoice() {
        String fileName = "savedTheme.thm";
        try {
            File theme = new File(System.getProperty("user.dir") + File.separator + fileName);
            ObjectInputStream inputStream = new ObjectInputStream(new FileInputStream(theme));
            String themeChoice = (String) inputStream.readObject();
            if (themeChoice != null) {
                if (themeChoice.equals("Light")) {
                    FlatLightLaf.setup();
                } else if (themeChoice.equals("Dark")) {
                    FlatDarkLaf.setup();
                } else {
                    changeToNimbus();

                }
            }
            SwingUtilities.updateComponentTreeUI(this);
        } catch (FileNotFoundException ex) {
        } catch (IOException ex) {

        } catch (ClassNotFoundException ex) {
        }
    }

