    private void importTextFileButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_importTextFileButtonActionPerformed
        JFileChooser fileChooser = new JFileChooser();
        FileNameExtensionFilter txtFilter = new FileNameExtensionFilter("Text Files (*.txt)", "txt");
        fileChooser.addChoosableFileFilter(txtFilter);
        fileChooser.setFileFilter(txtFilter);
        if (fileChooser.showOpenDialog(this) == JFileChooser.APPROVE_OPTION) {
            File textFile = fileChooser.getSelectedFile();
            String contents = "";
            try {
                FileReader reader = new FileReader(textFile);
                int character;
                while ((character = reader.read()) != -1) {
                    contents += (char) character;
                }
                submit(contents);
            } catch (FileNotFoundException ex) {
                Logger.getLogger(ImportDialog.class.getName()).log(Level.SEVERE, null, ex);
            } catch (IOException ex) {
                Logger.getLogger(ImportDialog.class.getName()).log(Level.SEVERE, null, ex);
            }
           
        }

    }//GEN-LAST:event_importTextFileButtonActionPerformed

    public void submit(String text) {
        ArrayList<String> terms = new ArrayList();
        ArrayList<String> definitions = new ArrayList();
        String[] lines = text.split("\n");
        for (String line : lines) {
            String[] parts = line.split("\t");

            if (parts.length == 2) {
                terms.add(parts[0]);
                definitions.add(parts[1]);
            }
        }
        if (!terms.isEmpty() && !definitions.isEmpty()) {
            name = (String) JOptionPane.showInputDialog(this, "Enter a name for your new study set.", "Study Set Name", JOptionPane.PLAIN_MESSAGE, null, null, null);
            if (name.isEmpty() || name == null) {
                name = "My New Study Set " + (sets.size() + 1);
            }
            newSet = new StudySet(terms, definitions, name);
            this.dispose();
        } else if (quizletTextArea.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please enter the text you got from Quizlet in the designated text field!", "Submit Error", JOptionPane.ERROR_MESSAGE);
        } else {
            JOptionPane.showMessageDialog(this, "Please make sure you pasted in the right text! (Refer to the instructions if you need help)", "Submit Error", JOptionPane.ERROR_MESSAGE);
        }

    }

